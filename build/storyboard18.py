def _tokens(runs):
    return [w for t, _ in runs for w in t.split() if w != "/"]


def _build_caps():
    """CAPS + words_cap.json: у каждого экранного слова — время начала своего слова из words.json."""
    words = _W["words"]
    assert sum(n for n, _ in PHRASES) == len(words), (sum(n for n, _ in PHRASES), len(words))
    caps, cap_words, i = [], [], 0
    for n, runs in PHRASES:
        ws = words[i:i + n]
        i += n
        if runs is None:
            continue
        toks, k = _tokens(runs), 0
        for tok in toks:
            m = tok.count("-") + 1 if tok.lower() in HYPH else 1
            cap_words.append(dict(word=tok, start=ws[k]["s"], end=ws[k + m - 1]["e"]))
            k += m
        assert k == n, (runs, n, k)
        caps.append((ws[0]["s"], ws[-1]["e"], [(t, c, 62) for t, c in runs], "A"))
    return caps, cap_words


